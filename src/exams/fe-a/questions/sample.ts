/** 問6 の配列の図（8 × 8）。marks は「＊」のある (i, j) */
function grid(marks: readonly (readonly [number, number])[]): { head: string[]; table: string[][] } {
  const on = new Set(marks.map(([i, j]) => `${i},${j}`));
  const idx = [0, 1, 2, 3, 4, 5, 6, 7];
  return {
    head: ["i＼j", ...idx.map(String)],
    table: idx.map(i => [String(i), ...idx.map(j => (on.has(`${i},${j}`) ? "＊" : ""))]),
  };
}
const range = (a: number, b: number) => Array.from({ length: b - a + 1 }, (_, k) => a + k);
